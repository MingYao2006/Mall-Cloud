/** 兼容 Map：省名 → 省对象 */
const PROVINCE_MAP = {}
PROVINCES.forEach((p) => {
  PROVINCE_MAP[p.name] = p
})

/**
 * 获取全部省份
 * @returns {string[]}
 */
export function getProvinces() {
  return PROVINCES.map((p) => p.name)
}

/**
 * 根据省份名获取城市列表
 * @param {string} provinceName
 * @returns {string[]}
 */
export function getCities(provinceName) {
  const province = PROVINCE_MAP[provinceName]
  if (!province) {
    return []
  }
  return province.cities.map((c) => c.name)
}

/**
 * 根据省份名 + 城市名获取区县列表
 * @param {string} provinceName
 * @param {string} cityName
 * @returns {string[]}
 */
export function getDistricts(provinceName, cityName) {
  const province = PROVINCE_MAP[provinceName]
  if (!province) {
    return []
  }
  const city = province.cities.find((c) => c.name === cityName)
  if (!city) {
    return []
  }
  return city.districts.slice()
}

/**
 * 取得完整地址（省 + 市 + 区 + 详细地址）
 *
 * 直辖市（北京市/上海市/天津市/重庆市）省市区同名，展示时需要去重，
 * 否则会出现「北京市北京市北京市」这种重复地址。
 *
 * @param {Object} parts
 * @param {string} parts.province
 * @param {string} parts.city
 * @param {string} parts.district
 * @param {string} parts.detail
 * @returns {string}
 */
export function buildFullAddress(parts) {
  const { province = '', city = '', district = '', detail = '' } = parts || {}
  const parts_ = []
  if (province) {
    parts_.push(province)
  }
  if (city && city !== province) {
    parts_.push(city)
  }
  if (district && district !== province && district !== city) {
    parts_.push(district)
  }
  if (detail) {
    parts_.push(detail)
  }
  return parts_.join('')
}

/**
 * 展开地址串（后端只存一个 receiverAddress 字段，前端展示时可再拆开）
 * @param {string} address
 * @returns {{ province: string, city: string, district: string, detail: string }}
 */
export function parseAddress(address) {
  const text = address || ''
  const province = getProvinces().find((name) => text.indexOf(name) === 0) || ''
  let rest = province ? text.slice(province.length) : text
  const city = getCities(province).find((name) => rest.indexOf(name) === 0) || ''
  if (city) {
    rest = rest.slice(city.length)
  }
  const district = getDistricts(province, city).find((name) => rest.indexOf(name) === 0) || ''
  if (district) {
    rest = rest.slice(district.length)
  }
  return { province, city, district, detail: rest }
}

export default {
  getProvinces,
  getCities,
  getDistricts,
  buildFullAddress,
  parseAddress
}
